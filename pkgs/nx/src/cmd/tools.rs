//! Small commands: clean, optimise, diff, lint, fmt.

use crate::sh::{self, Paths, cmd};
use crate::ui;
use anyhow::Result;

pub fn clean(nh_args: &[String]) -> Result<()> {
    let mut c = cmd("nh");
    c.args(["clean", "all"]);
    if nh_args.is_empty() {
        c.args(["--keep", "4"]);
    } else {
        c.args(nh_args);
    }
    sh::run_or_exit(&mut c)
}

pub fn optimise() -> Result<()> {
    ui::step("Optimising the store (hard-linking identical files)");
    sh::run_or_exit(cmd("nix").args(["store", "optimise"]))
}

pub fn diff() -> Result<()> {
    ui::step("Changes since boot (booted -> current system)");
    sh::run_or_exit(cmd("nvd").args(["diff", "/run/booted-system", "/run/current-system"]))
}

pub fn lint(p: &Paths) -> Result<()> {
    ui::step("statix (anti-patterns)");
    if sh::run(cmd("statix").args(["check", "."]).current_dir(&p.dots))? {
        ui::good("nothing to fix");
    } else {
        ui::caution("statix found issues");
    }
    // hardware-configuration.nix is generated by nixos-generate-config
    ui::step("deadnix (unused code)");
    let hw = p.dots.join("hosts/mntbnd/hardware-configuration.nix");
    if sh::run(
        cmd("deadnix")
            .arg("--fail")
            .arg("--exclude")
            .arg(hw)
            .arg(&p.dots),
    )? {
        ui::good("nothing unused");
    } else {
        ui::caution("deadnix found unused code");
    }
    Ok(())
}

pub fn fmt(p: &Paths) -> Result<()> {
    ui::step("Formatting with alejandra");
    sh::run_or_exit(cmd("alejandra").arg("--quiet").args(p.nix_dirs()))?;
    ui::good("done");
    Ok(())
}
